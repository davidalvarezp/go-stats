// Server encapsulates the HTTP API and the embedded dashboard.
type Server struct {
	port      int
	collector *collector.Collector
	httpSrv   *http.Server
}

// NewServer initializes a new go-stats server instance.
// Parameters:
//   - port: The TCP port to listen on (e.g. 10590).
func NewServer(port int) *Server {
	return &Server{
		port:      port,
		collector: collector.NewCollector(),
	}
}

// Start registers HTTP routes and begins listening for requests.
func (s *Server) Start() error {
	mux := http.NewServeMux()

	// -------------------------------------------------------------------------
	// REST API Endpoints
	// -------------------------------------------------------------------------
	mux.HandleFunc("/api/metrics", s.handleMetrics)
	mux.HandleFunc("/api/processes", s.handleProcesses)
	mux.HandleFunc("/api/process/signal", s.handleProcessSignal)
	mux.HandleFunc("/api/systemd/status", s.handleSystemdStatus)
	mux.HandleFunc("/api/systemd/action", s.handleSystemdAction)
	mux.HandleFunc("/api/health", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		fmt.Fprintf(w, `{"status":"ok","app":"go-stats","port":%d,"timestamp":%d}`, s.port, time.Now().Unix())
	})

	// -------------------------------------------------------------------------
	// Embedded Web Dashboard
	// -------------------------------------------------------------------------
	// Serves the self-contained dashboard generated by ui.go.
	// Does not require any external HTML, CSS, or JS files on disk.
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Write([]byte(GetDashboardHTML(s.port)))
	})

	addr := fmt.Sprintf("0.0.0.0:%d", s.port)
	s.httpSrv = &http.Server{
		Addr:         addr,
		Handler:      corsMiddleware(mux),
		ReadTimeout:  10 * time.Second,
		WriteTimeout: 10 * time.Second,
	}

	log.Printf("========================================================\n")
	log.Printf("HTTP Server listening on: http://localhost:%d\n", s.port)
	log.Printf("========================================================\n")
	return s.httpSrv.ListenAndServe()
}

// handleMetrics returns a real-time JSON snapshot of CPU, Memory, Disks, Network, and Load.
func (s *Server) handleMetrics(w http.ResponseWriter, r *http.Request) {
	snap, err := s.collector.Collect()
	if err != nil {
		http.Error(w, fmt.Sprintf(`{"error":"%s"}`, err.Error()), http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(snap)
}

// handleProcesses returns the active process list scanned from /proc, sorted by CPU usage.
func (s *Server) handleProcesses(w http.ResponseWriter, r *http.Request) {
	mem, _ := s.collector.Collect()
	totalMem := uint64(0)
	if mem != nil {
		totalMem = mem.Memory.Total
	}

	procs, summary, err := s.collector.CollectProcesses(totalMem)
	if err != nil {
		http.Error(w, fmt.Sprintf(`{"error":"%s"}`, err.Error()), http.StatusInternalServerError)
		return
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"processes": procs,
		"summary":   summary,
		"count":     len(procs),
	})
}

// handleProcessSignal sends standard POSIX signals (SIGTERM, SIGKILL) to a process.
func (s *Server) handleProcessSignal(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, `{"error":"Method not allowed"}`, http.StatusMethodNotAllowed)
		return
	}

	var req struct {
		PID    int    `json:"pid"`
		Signal string `json:"signal"` // "SIGTERM", "SIGKILL"
	}

	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, `{"error":"Invalid request payload"}`, http.StatusBadRequest)
		return
	}

	// Safety check: protect init (PID 1) and kernel tasks
	if req.PID <= 1 {
		http.Error(w, `{"error":"Cannot send signal to protected system PID <= 1"}`, http.StatusForbidden)
		return
	}

	sig := syscall.SIGTERM
	if req.Signal == "SIGKILL" {
		sig = syscall.SIGKILL
	}

	proc, err := os.FindProcess(req.PID)
	if err != nil {
		http.Error(w, fmt.Sprintf(`{"error":"Process not found: %s"}`, err.Error()), http.StatusNotFound)
		return
	}

	if err := proc.Signal(sig); err != nil {
		http.Error(w, fmt.Sprintf(`{"error":"Failed to signal process: %s"}`, err.Error()), http.StatusInternalServerError)
		return
	}

	w.Header().Set("Content-Type", "application/json")
	fmt.Fprintf(w, `{"success":true,"pid":%d,"signal":"%s"}`, req.PID, req.Signal)
}

// handleSystemdStatus queries systemctl to verify if go-stats.service is active.
func (s *Server) handleSystemdStatus(w http.ResponseWriter, r *http.Request) {
	status, active, err := service.GetServiceStatus()
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"unit":      "go-stats.service",
		"status":    status,
		"active":    active,
		"error":     fmt.Sprintf("%v", err),
		"timestamp": time.Now().Unix(),
	})
}

// handleSystemdAction executes systemctl control verbs (start, stop, restart, enable).
func (s *Server) handleSystemdAction(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, `{"error":"Method not allowed"}`, http.StatusMethodNotAllowed)
		return
	}
	var req struct {
		Action string `json:"action"` // start, stop, restart, enable, disable
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, `{"error":"Invalid payload"}`, http.StatusBadRequest)
		return
	}

	out, err := service.ControlService(req.Action)
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"action":  req.Action,
		"success": err == nil,
		"output":  out,
	})
}

// corsMiddleware injects CORS and standard security headers.
func corsMiddleware(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Access-Control-Allow-Origin", "*")
		w.Header().Set("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
		w.Header().Set("Access-Control-Allow-Headers", "Content-Type, Authorization")
		w.Header().Set("X-Content-Type-Options", "nosniff")
		w.Header().Set("X-Frame-Options", "SAMEORIGIN")

		if r.Method == http.MethodOptions {
			w.WriteHeader(http.StatusOK)
			return
		}
		next.ServeHTTP(w, r)
	})
}
